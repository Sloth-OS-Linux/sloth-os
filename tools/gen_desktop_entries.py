def _open_helper_suggestions():
    """(file types, app id) of the "I can't open this file" helper (open_helper.py: SUGGESTIONS)."""
    import ast
    src = (TOOLS / "sloth-center/sloth_center/open_helper.py").read_text(encoding="utf-8")
    consts = {}
    for node in ast.parse(src).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name in ("OFFICE", "IMAGES", "MEDIA"):
                consts[name] = ast.literal_eval(node.value)
            elif name == "SUGGESTIONS":
                found = []
                for item in node.value.elts:
                    first = item.elts[0]
                    types = consts[first.id] if isinstance(first, ast.Name) else ast.literal_eval(first)
                    found.append((tuple(types), ast.literal_eval(item.elts[1])))
                return found
    raise SystemExit("open_helper.py: SUGGESTIONS not found")


OPEN_HELPER_SUGGESTIONS = _open_helper_suggestions()
OPEN_HELPER_TYPES = [t for types, _app in OPEN_HELPER_SUGGESTIONS for t in types]

